-- Tests: spoilers: the presets, choices by hand, hints, and what the player has found.

test("spoilers start in Guide, where nothing is held back and nothing needs asking", function()
    local ns = createAddon()
    ns.Spoilers.create()
    expectEqual(ns.Spoilers.getPreset(), "guide", "the default")
    expectEqual(ns.Spoilers.isActive(), false, "nothing held back")
    expectEqual(ns.Spoilers.getKey(), "guide", "a key that never changes")
    expectEqual(ns.Spoilers.get("objectives", 783), "exact", "exact spawns")
    expectEqual(ns.Spoilers.isShown("pickup"), true, "quests to pick up shown")
    expectEqual(ns.Spoilers.isExplored(85, 50, 50), true, "no fog asked about")
end)

test("a preset sets every kind, and a choice by hand makes it custom until set back", function()
    local ns = createAddon()
    ns.Spoilers.create()
    ns.Spoilers.setPreset("explorer")
    expectEqual(ns.Spoilers.getPreset(), "explorer", "the preset")
    expectEqual(ns.Spoilers.isActive(), true, "something held back")
    expectEqual(ns.Spoilers.getChoice("objectives"), "found", "objectives where found")
    expectEqual(ns.Spoilers.getChoice("pickup"), "met", "givers met")
    local key = ns.Spoilers.getKey()
    ns.Spoilers.setChoice("rewards", "hidden")
    expectEqual(ns.Spoilers.getPreset(), "custom", "changed by hand")
    expectEqual(ns.Spoilers.getChoice("rewards"), "hidden", "the choice")
    expectEqual(ns.Spoilers.getKey() ~= key, true, "the key moved on")
    ns.Spoilers.setChoice("rewards", "shown")
    expectEqual(ns.Spoilers.getPreset(), "explorer", "the preset's own choice takes the change back")
    ns.Spoilers.setChoice("rewards", "nonsense")
    expectEqual(ns.Spoilers.getChoice("rewards"), "shown", "an unknown choice is ignored")
    ns.Spoilers.setPreset("guide")
    expectEqual(ns.Spoilers.isActive(), false, "back to everything")
end)

test("the spoiler choice is kept per character", function()
    local ns = createAddon()
    ns.Spoilers.create()
    ns.Spoilers.setPreset("purist")
    local savedName = UnitName
    UnitName = function(unit)
        return unit == "player" and "Alt" or nil
    end
    ns.Spoilers.create()
    expectEqual(ns.Spoilers.getPreset(), "guide", "another character starts in Guide")
    UnitName = savedName
    ns.Spoilers.create()
    expectEqual(ns.Spoilers.getPreset(), "purist", "this one kept Purist")
end)

test("a hint lifts one quest's choice a step at a time, and marks it as hinted", function()
    local ns = createAddon()
    ns.Spoilers.create()
    ns.Spoilers.setPreset("purist")
    expectEqual(ns.Spoilers.get("objectives", 783), "hidden", "hidden at first")
    expectEqual(ns.Spoilers.canHint(783), true, "a hint can help")
    ns.Spoilers.giveHint(783)
    expectEqual(ns.Spoilers.getHint(783), 1, "the zone")
    expectEqual(ns.Spoilers.get("objectives", 783), "hidden", "the zone alone draws nothing")
    ns.Spoilers.giveHint(783)
    expectEqual(ns.Spoilers.get("objectives", 783), "rough", "roughly where")
    expectEqual(ns.Spoilers.get("turnIn", 783), "shown", "and the turn-in")
    expectEqual(ns.Spoilers.get("drops", 783), "names", "who drops it, without chances")
    ns.Spoilers.giveHint(783)
    expectEqual(ns.Spoilers.get("objectives", 783), "exact", "exactly where")
    expectEqual(ns.Spoilers.get("drops", 783), "chances", "with chances")
    expectEqual(ns.Spoilers.canHint(783), false, "nothing more to show")
    expectEqual(ns.Spoilers.get("objectives", 999), "hidden", "another quest is not lifted")
    expectEqual(ns.Spoilers.wasHinted(783), true, "counted as hinted")
    expectEqual(ns.Spoilers.wasHinted(999), false, "the other not")
end)

test("a hint never lowers what a choice already shows", function()
    local ns = createAddon()
    ns.Spoilers.create()
    ns.Spoilers.setPreset("hints")
    ns.Spoilers.giveHint(783, 2)
    expectEqual(ns.Spoilers.get("objectives", 783), "rough", "rough stays rough")
    expectEqual(ns.Spoilers.get("drops", 783), "names", "names stay names")
end)

test("Explorer remembers where an objective moved on, once per place", function()
    local ns, state = createAddon()
    ns.Spoilers.create()
    ns.Spoilers.setPreset("explorer")
    setQuest(state, 783, false, { killObjective(0, 5) })
    state.playerMapId, state.playerX, state.playerY = 1420, 0.40, 0.60
    ns.Spoilers.reset()
    for _, module in ipairs(ns.getModules()) do
        if module.name == "Spoilers" then
            module.invalidate()
            expectEqual(#ns.Spoilers.getFoundPlaces(783, 1), 0, "nothing found before a count goes up")
            state.questLog[783].objectives = { killObjective(1, 5) }
            module.invalidate()
            local places = ns.Spoilers.getFoundPlaces(783, 1)
            expectEqual(#places, 1, "found where the player stands")
            expectEqual(places[1].x, 40, "across")
            expectEqual(places[1].y, 60, "down")
            state.questLog[783].objectives = { killObjective(2, 5) }
            state.playerX = 0.405
            module.invalidate()
            expectEqual(#ns.Spoilers.getFoundPlaces(783, 1), 1, "a step away is the same place")
            state.questLog[783].objectives = { killObjective(3, 5) }
            state.playerX = 0.55
            module.invalidate()
            expectEqual(#ns.Spoilers.getFoundPlaces(783, 1), 2, "elsewhere is another")
            expectEqual(ns.Spoilers.hasFoundAny(783), true, "the quest has found places")
        end
    end
end)

test("Explorer remembers creatures killed, and nothing in Guide", function()
    local ns = createAddon()
    ns.Spoilers.create()
    ns.Spoilers.noteKill(3244)
    expectEqual(ns.Spoilers.hasKilled(3244), false, "Guide keeps no memory")
    ns.Spoilers.setPreset("explorer")
    ns.Spoilers.noteKill(3244)
    expectEqual(ns.Spoilers.hasKilled(3244), true, "killed")
    expectEqual(ns.Spoilers.hasKilled(3245), false, "another not")
end)

test("/omq spoilers picks a preset by name", function()
    local ns = createAddon()
    ns.Spoilers.create()
    ns.Spoilers.handleCommand("Hints")
    expectEqual(ns.Spoilers.getPreset(), "hints", "picked")
    ns.Spoilers.handleCommand("nonsense")
    expectEqual(ns.Spoilers.getPreset(), "hints", "an unknown word changes nothing")
end)
